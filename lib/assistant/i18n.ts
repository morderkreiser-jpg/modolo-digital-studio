export const DEFAULT_STRINGS: Record<AssistantLocale, AssistantStrings> = { en: EN, de: DE, it: IT };

/** Flat overrides of one locale: "subtitle", "form.title", "chatErrors.timeout" → text. */
export type LocaleStringOverrides = Partial<Record<string, string>>;

/** Per-locale overrides, the shape of TenantConfig.strings / AssistantPublicConfig.strings. */
export type AssistantStringOverrides = Partial<Record<AssistantLocale, LocaleStringOverrides>>;

type StringTree = { [key: string]: string | StringTree };

/** The per-locale map has only locale keys with object values; a flat map has string values. */
function overridesFor(
  locale: AssistantLocale,
  overrides: AssistantStringOverrides | LocaleStringOverrides,
): LocaleStringOverrides | undefined {
  const entries = Object.entries(overrides);
  const perLocale = entries.every(([key, value]) => isAssistantLocale(key) && typeof value === "object" && value !== null);
  return perLocale ? (overrides as AssistantStringOverrides)[locale] : (overrides as LocaleStringOverrides);
}

/**
 * The strings for `locale` with the tenant's overrides applied. `overrides` is either the
 * per-locale map (as in AssistantPublicConfig.strings) or the flat overrides of this locale. An
 * override is used only when its key names an existing string (unknown keys and non-string
 * values are ignored, so a typo cannot add keys or reach the prototype chain). Never mutates
 * DEFAULT_STRINGS.
 */
export function getStrings(
  locale: AssistantLocale,
  overrides?: AssistantStringOverrides | LocaleStringOverrides,
): AssistantStrings {
  const base = DEFAULT_STRINGS[locale] ?? DEFAULT_STRINGS.en;
  const patch = overrides ? overridesFor(locale, overrides) : undefined;
  if (!patch) return base;

  const result = cloneTree(base as unknown as StringTree);
  for (const [path, value] of Object.entries(patch)) {
    if (typeof value !== "string" || !value.trim()) continue;
    const keys = path.split(".");
    const last = keys.pop();
    let node: StringTree | undefined = result;
    for (const key of keys) {
      const next: string | StringTree | undefined = Object.hasOwn(node, key) ? node[key] : undefined;
      node = typeof next === "object" ? next : undefined;
      if (!node) break;
    }
    if (node && last && Object.hasOwn(node, last) && typeof node[last] === "string") node[last] = value;
  }
  return result as unknown as AssistantStrings;
}

function cloneTree(tree: StringTree): StringTree {
  const copy: StringTree = {};
  for (const [key, value] of Object.entries(tree)) copy[key] = typeof value === "string" ? value : cloneTree(value);
  return copy;
}
