// region IT included (live rule since 2026-07-10, as on /preise).
//
// What the credit, its screen-reader sentence and the Impressum name comes ONLY from FILM.projects
// (lib/film-media.ts, written by the film build from the published variant), never from data/projects.ts:
// a site that is not in the published film is never named here.
//
// Contract with the nav: the <section> carries `data-nav-overlay`. The nav (and the mobile sticky bar)
// observe it and read the sheet overlap from section 01, the hero's next sibling in components/home.tsx
// (useFilmZone in components/site-nav.tsx): the bar turns cream exactly when the cream sheet's top
// edge passes under the nav. The overlap is --sheet-radius (28 px, 20 px under PORTRAIT_MQ). Nothing
// may be rendered after the <section> in this component.

const CELL_CLASS: Partial<Record<RailKey, string>> = { business: s.cellBusiness, fixed: s.cellFix };

/** «a und b», «a, b und c» (COPY §3). */
function joinNames(names: readonly string[], and: string): string {
  return names.length < 2 ? names.join("") : `${names.slice(0, -1).join(", ")} ${and} ${names[names.length - 1]}`;
}

let warnedTimeline = false;

/**
 * Build guards (SPEC §2.4). They run when the page is prerendered, so `next build` fails instead of
 * shipping a credit that names the wrong site, or a film that shows ZUMOVE before Marco has said yes.
 */
function assertFilmContract(): void {
  const inFilm = new Set<ProjectId>(FILM.projects.map((p) => p.id));
  for (const p of FILM.projects) {
    for (const l of LOCALES) {
      if (!HERO[l].credit[p.id]) {
        throw new Error(`Hero film: no credit label for «${p.id}» (${l}) in content/home/hero.ts`);
      }
    }
  }
  for (const shot of FILM.shots) {
    if (!inFilm.has(shot.credit) || (shot.project !== null && !inFilm.has(shot.project))) {
      throw new Error(`Hero film: shot ${shot.slot} names a site that is not in FILM.projects (lib/film-media.ts)`);
    }
  }
  const zumovePending = PROJECTS.some((p) => p.id === "zumove" && p.approval !== undefined);
  if (zumovePending && (FILM.variant !== "nozu" || inFilm.has("zumove"))) {
    throw new Error("Hero film shows ZUMOVE without Marco's written OK (data/projects.ts approval)");
  }
  // The timeline must describe the published files: the shots run from frame 0 to FILM.frames without a gap.
  // Until the film build regenerates lib/film-media.ts, its stub pairs the v2 timeline (345 frames) with the v1
  // files (325 frames), and the credit would name BJ Studio over another film. A production build refuses
  // that; the dev server only warns, so the page stays usable while the film is being made.
  const contiguous = FILM.shots.every((sh, i) => (i === 0 ? sh.startFrame === 0 : sh.startFrame === FILM.shots[i - 1].endFrame));
  const lastFrame = FILM.shots[FILM.shots.length - 1]?.endFrame;
  if (!contiguous || lastFrame !== FILM.frames) {
    const msg = `Hero film: FILM.shots cover frames 0–${lastFrame} but the published film has ${FILM.frames} frames (lib/film-media.ts not regenerated by tools/film/build-hero-film.mjs?)`;
    if (process.env.NODE_ENV === "production") throw new Error(msg);
    if (!warnedTimeline) {
      warnedTimeline = true;
      console.warn(msg);
    }
  }
}

export default function HeroFilm({ lang }: { lang: Locale }) {
  assertFilmContract();

  const t = HERO[lang];
  // CHF for every region: only the WhatsApp number follows MDS_REGION.
  const ch = buildPrices("ch", lang);
  const priceCh = t.priceLine1(ch).split(" · ");
  const railCh = t.rail(ch);
  // The grain tile is optional in the film manifest: no tile, no layer.
  const grain = (FILM as { grain?: { src: string } }).grain;

  // The live credit (SPEC §2.4, COPY §2–3): one row per site of the published film, in film order.
  const entries = FILM.projects.map((p) => ({ id: p.id, host: p.host, label: t.credit[p.id] ?? "" }));
  const sr = `${t.creditSr.prefix} ${joinNames(
    entries.map((e) => `${e.host} (${e.label.replace(" · ", ", ")})`),
    t.creditSr.and,
  )}.`;
  const credit = {
    entries,
    live: t.creditLive,
    sr,
    posterShot: filmShotAt(FILM.startAt[lang]),
    stackClassName: s.creditStack,
    rowClassName: s.creditRow,
    dotClassName: s.creditDot,
    liveClassName: s.creditLive,
    hostClassName: s.creditHost,
    whatClassName: s.creditWhat,
    srClassName: s.srOnly,
  };

  return (
    <section data-film data-nav-overlay aria-labelledby="hero-title" className={s.hero}>
      {/* 1 poster → 2 video. The film shows his real websites; the hands and rooms are licensed stock,
          credited in the Impressum. Decorative for assistive tech: the credit link names what is on screen. */}
      <div className={s.media} aria-hidden="true">
        <FilmPoster lang={lang} className={s.fill} />
        <BackgroundFilm lang={lang} className={s.fill} />
      </div>

      {/* 3 scrims (Layout L; Layout P anchors its scrims to the text groups) → 4 grain */}
      <div className={s.scrimTop} aria-hidden="true" />
      <div className={s.scrimLeft} aria-hidden="true" />
      <div className={s.scrimBottom} aria-hidden="true" />
      {grain ? (
        <div className={s.grain} data-film-grain="" style={{ backgroundImage: `url(${grain.src})` }} aria-hidden="true" />
      ) : null}

      {/* 5 content */}
      <div className={s.content}>
        <div className={s.top}>
          <h1 id="hero-title" className={s.h1}>
            <span className={s.kicker}>{t.kicker}</span>{" "}
            <span className={s.line1}>{t.h1[0]}</span>{" "}
            <span className={s.line2}>{t.h1[1]}</span>
          </h1>
          {/* Layout L: the credit is the H1's footnote */}
          <FilmCredit layout="L" className={`${s.credit} ${s.creditL}`} {...credit} />
        </div>

        {/* Layout P: the film band between the headline and the copy */}
        <div className={s.band} aria-hidden="true" />

        <div className={s.bottom}>
          {/* Layout P: the credit sits under the band, above the sub */}
          <FilmCredit layout="P" className={`${s.credit} ${s.creditP}`} {...credit} />

          <p className={s.sub}>
            {t.sub[0]}
            <span className={s.subL}>{t.sub[1]}</span>
          </p>

          <p className={s.price1}>
            {priceCh.map((item, i) => (
              <span key={item}>
                {i > 0 ? " · " : null}
                <span className={s.nowrap}>{item}</span>
              </span>
            ))}
          </p>
          <p className={s.fixed}>{t.priceLine2}</p>

          <div className={s.actions}>
            <RegionLink
              hrefCh={waHref(PREFILL[lang].hero, "ch")}
              hrefIt={waHref(PREFILL[lang].hero, "it")}
              target="_blank"
              rel="noopener noreferrer"
              className={s.cta}
              data-cta="hero-whatsapp"
            >
              <WhatsAppGlyph className={s.ctaIcon} />
              <span>{t.cta}</span>
            </RegionLink>
            <a href="#gratis-check" className={s.secondary}>
              <span>{t.secondary}</span>
              <ArrowDown className={s.arrow} />
            </a>
          </div>

          {/* Layout L: the rail (founder · prices · Fixpreis · toggle). Layout P: founder chip; the toggle is
              painted at the right end of the credit row (out of the AI launcher's corner), same DOM place. */}
          <div className={s.rail}>
            <div className={s.founder}>
              {/* eslint-disable-next-line @next/next/no-img-element -- 13 KB avatar that must paint on the first frame; next/image would add a lazy, optimizer round-trip */}
              <img
                src="/founder-avatar.webp"
                alt=""
                width={44}
                height={44}
                loading="eager"
                decoding="async"
                className={s.avatar}
              />
              <span className={s.founderText}>
                <span className={s.founderName}>{t.chipName}</span>
                <span className={s.reply}>{t.chipReply}</span>
              </span>
            </div>

            <dl className={s.cells}>
              {railCh.map((cell) => {
                const extra = CELL_CLASS[cell.key];
                return (
                  <div key={cell.key} className={extra ? `${s.cell} ${extra}` : s.cell}>
                    <dt className={s.cellLabel}>{cell.label}</dt>
                    <dd className={s.cellValue}>{cell.value}</dd>
                  </div>
                );
              })}
            </dl>

            <div className={s.toggleCell}>
              <FilmToggle
                labels={t.toggle}
                className={s.toggle}
                labelClassName={s.toggleLabel}
                iconClassName={s.toggleIcon}
              />
            </div>
          </div>
        </div>
      </div>
    </section>
  );
}

