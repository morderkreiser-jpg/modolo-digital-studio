// The homepage hero (film v2, «Websites wie diese.»): a full-screen film that shows Francesco's real,
// live websites on laptops and phones, and the offer on top. Under the H1 a live credit names the site
// on screen and what it is; it switches on the cut.
// Server component. Everything a visitor reads is in the server HTML and paints on the first frame
// (no opacity or transform entrance anywhere): LCP is the h1 / sub, the poster covers the viewport
// and is excluded from LCP. Client islands: the <video>, the live credit, the pause/play toggle, and
